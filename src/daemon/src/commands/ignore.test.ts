type ImportCase = {
  name: string;
  before?: string;
  script: string;
  expect: {
    summary: { imported: number; present: number; skipped: number };
    warnings?: number;
    contains?: string[];
    absent?: string[];
  };
};

const IMPORT_CASES: ImportCase[] = [
  {
    name: "novel entries import, builtin-covered ones skip",
    script: [
      "IgnorePath '/swapfile'",
      "IgnorePath '/etc/machine-id'",
      "IgnorePath '/var/log/pacman.log'",
      "IgnorePath '*.pacsave'",
      "IgnoreFile /etc/group",
      "IgnorePackage --foreign neofetch",
    ].join("\n"),
    expect: {
      summary: { imported: 2, present: 0, skipped: 4 },
      contains: ["/swapfile", "neofetch"],
      absent: ["/etc/machine-id", "pacman.log", "*.pacsave", "/etc/group"],
    },
  },
  {
    name: "existing user entries count as present",
    before: "files: [/swapfile]\n",
    script: "IgnorePath '/swapfile'\nIgnorePath '/boot/vmlinuz-linux'\n",
    expect: {
      summary: { imported: 1, present: 1, skipped: 0 },
      contains: ["/swapfile", "/boot/vmlinuz-linux"],
    },
  },
  {
    name: "duplicates within the script dedupe",
    script: "IgnorePath /usr/bin/groupmems\nIgnorePath /usr/bin/groupmems\n",
    expect: {
      summary: { imported: 1, present: 1, skipped: 0 },
      contains: ["/usr/bin/groupmems"],
    },
  },
  {
    name: "warnings surface but entries still import",
    script: "IgnorePath '/etc/*-'\nFooBar baz\n",
    expect: {
      summary: { imported: 1, present: 0, skipped: 0 },
      warnings: 2,
      contains: ["/etc/*-"],
    },
  },
  {
    name: "subtree globs translate before writing",
    script: "IgnorePath '/etc/mullvad-vpn/*'\n",
    expect: {
      summary: { imported: 1, present: 0, skipped: 0 },
      contains: ["/etc/mullvad-vpn/**"],
    },
  },
];

const runImportCase = (c: ImportCase) => {
  if (c.before !== undefined) fs.writeFileSync(paths.etc.ignoreYaml, c.before);
  const s = runImport(c.script);
  expect({ imported: s.imported, present: s.present, skipped: s.skipped }).toEqual(
    c.expect.summary,
  );
  if (c.expect.warnings !== undefined) expect(s.warnings).toHaveLength(c.expect.warnings);
  const text = ignorefile.read().text;
  for (const sub of c.expect.contains ?? []) expect(text).toContain(sub);
  for (const sub of c.expect.absent ?? []) expect(text).not.toContain(sub);
};

for (const c of IMPORT_CASES) {
  test(`import: ${c.name}`, () => runImportCase(c));
}

test("import round-trips into an effective matcher", () => {
  runImport("IgnorePath '/var/*'\nIgnorePath '*.pacnew'\n");
  const m = ignore.compile(ignorefile.effective());
  expect(
    m.ignores({ type: "stray", id: "/var/lib/libvirt/x", field: "exists", expected: null, actual: null }),
  ).toBe(true);
  expect(m.prunes).toContain("/var");
});
